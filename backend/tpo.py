def _prefer_table(tpo, sex):
    """공통(any) 위에 성별 표를 덮어쓴 {부위: {속성: {값: 가중치}}}"""
    t = PREFER.get(tpo, {}); out = {}
    for layer in (t.get("any", {}), t.get(sex, {})):
        for part, attrs in layer.items():
            for k, vals in attrs.items(): out.setdefault(part, {}).setdefault(k, {}).update(vals)
    return out


def prefer_score(tpo, part, attrs, sex="F"):
    """상황 우선 점수 (속성별 가중치 합)"""
    return sum(vals.get(attrs.get(k), 0.0) for k, vals in _prefer_table(tpo, sex).get(part, {}).items())


def preferred(tpo, sex="F", min_w=0.5):
    """화면용: 이 상황에서 크게 우선한 값들 ['셔츠', '재킷', ...]"""
    out = []
    for part, attrs in _prefer_table(tpo, sex).items():
        for k, vals in attrs.items():
            for v, w in sorted(vals.items(), key=lambda kv: -kv[1]):
                name = v if k == "카테고리" else f"{v} {part}"
                if w >= min_w and name not in out: out.append(name)
    return out


def excluded(tpo, part, attrs):
    ex = EXCLUDE.get(tpo, {}).get(part, {})
    return any(attrs.get(k) in vs for k, vs in ex.items())


def shoes_excluded(tpo):
    return set(EXCLUDE.get(tpo, {}).get("신발", []))


def styles_for(tpo, sex="F"):
    t = TPO.get(tpo)
    if not t: return None
    return list(t.get(sex) or t.get("any") or [])


